#!/bin/bash

###############################################
# CREATE OUTPUT DIRECTORY
###############################################

mkdir -p rg

###############################################
# INPUT FILES
###############################################

TPR="md.tpr"
XTC="npt_stat_400K_14.xtc"

###############################################
# LOOP OVER INDEX FILES
###############################################

for i in $(seq 1 200); do

    NDX="pla_-${i}.ndx"
    OUT="rg/pla${i}.xvg"

    ###########################################
    # CHECK FILE EXISTS
    ###########################################

    if [[ ! -f "$NDX" ]]; then
        echo "Missing $NDX → skipping"
        continue
    fi

    echo "Running $NDX"

    ###########################################
    # RUN GROMACS
    ###########################################

    gmx gyrate \
        -f "$XTC" \
        -s "$TPR" \
        -n "$NDX" \
        -o "$OUT" \
        #-b 1 -e 10000

done
